package com.example.ui.components

import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import androidx.compose.ui.window.Dialog
import com.example.data.model.TokenTier
import com.example.engine.AuthAndAccessManager
import com.example.ui.theme.*

/**
 * Dialog enabling User to activate / redeem an access token (L1, L2, L3)
 * generated by Admin.
 */
@Composable
fun UserTokenActivationDialog(
    isSwahili: Boolean,
    onDismiss: () -> Unit
) {
    val context = LocalContext.current
    val authManager = remember { AuthAndAccessManager.getInstance(context) }
    val currentUser by authManager.currentUser.collectAsState()

    var tokenInput by remember { mutableStateOf("") }
    var resultMessage by remember { mutableStateOf<String?>(null) }
    var isSuccess by remember { mutableStateOf(false) }

    Dialog(onDismissRequest = onDismiss) {
        Card(
            colors = CardDefaults.cardColors(containerColor = SurfaceCard),
            border = androidx.compose.foundation.BorderStroke(1.5.dp, GlassmorphismDefaults.GlassBorderGold),
            shape = RoundedCornerShape(16.dp),
            modifier = Modifier.fillMaxWidth().padding(12.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(18.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.VpnKey, contentDescription = null, tint = AccentGold, modifier = Modifier.size(24.dp))
                        Spacer(modifier = Modifier.width(8.dp))
                        Text(
                            text = if (isSwahili) "WEKA TOKEN YA MFUMO" else "ENTER SYSTEM TOKEN",
                            style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.Black,
                            color = AccentGold
                        )
                    }
                    IconButton(onClick = onDismiss, modifier = Modifier.size(24.dp)) {
                        Icon(Icons.Default.Close, contentDescription = "Close", tint = TextMuted)
                    }
                }

                Spacer(modifier = Modifier.height(10.dp))

                // Current Active Token Status
                Surface(
                    color = SurfaceElevated,
                    shape = RoundedCornerShape(8.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(modifier = Modifier.padding(10.dp)) {
                        Text(
                            text = if (isSwahili) "HALI YA TOKEN YAKO YA SASA:" else "CURRENT ACCESS TIER:",
                            fontSize = 10.sp,
                            fontWeight = FontWeight.Bold,
                            color = TextMuted
                        )
                        val activeTier = currentUser?.tokenTier
                        if (activeTier != null) {
                            Text(
                                text = "✅ ${activeTier.titleSwahili}",
                                fontWeight = FontWeight.Black,
                                color = AccentNeonGreen,
                                fontSize = 13.sp
                            )
                            Text(
                                text = "Boti: ${activeTier.maxActiveBots} | Max: $${String.format("%,.0f", activeTier.maxCapitalUsd)}",
                                fontSize = 10.sp,
                                color = AccentCyan
                            )
                        } else {
                            Text(
                                text = if (isSwahili) "Huna Token iliyowashwa (Wasiliana na Admin)" else "No Active Token (Contact Admin)",
                                fontWeight = FontWeight.Bold,
                                color = AccentOrange,
                                fontSize = 12.sp
                            )
                        }
                    }
                }

                Spacer(modifier = Modifier.height(12.dp))

                Text(
                    text = if (isSwahili) "Ingiza Token uliyopewa na Admin (mfano: ESMH-L1-XXXX):" else "Enter Admin Token (e.g. ESMH-L1-XXXX):",
                    style = MaterialTheme.typography.labelSmall,
                    color = TextWhite
                )
                Spacer(modifier = Modifier.height(4.dp))
                OutlinedTextField(
                    value = tokenInput,
                    onValueChange = { tokenInput = it.uppercase() },
                    placeholder = { Text("ESMH-L1-XXXX", color = TextMuted, fontSize = 12.sp) },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = AccentGold,
                        unfocusedBorderColor = BorderSubtle,
                        focusedTextColor = TextWhite,
                        unfocusedTextColor = TextWhite
                    )
                )

                // Quick presets helper for demo testing
                Spacer(modifier = Modifier.height(8.dp))
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(4.dp)
                ) {
                    Surface(
                        onClick = { tokenInput = "ESMH-L1-BEST-7890" },
                        color = SurfaceElevated,
                        shape = RoundedCornerShape(4.dp),
                        modifier = Modifier.weight(1f)
                    ) {
                        Text("L1 Best", fontSize = 9.sp, fontWeight = FontWeight.Bold, color = AccentGold, modifier = Modifier.padding(4.dp))
                    }
                    Surface(
                        onClick = { tokenInput = "ESMH-L2-NORM-4521" },
                        color = SurfaceElevated,
                        shape = RoundedCornerShape(4.dp),
                        modifier = Modifier.weight(1f)
                    ) {
                        Text("L2 Normal", fontSize = 9.sp, fontWeight = FontWeight.Bold, color = AccentCyan, modifier = Modifier.padding(4.dp))
                    }
                    Surface(
                        onClick = { tokenInput = "ESMH-L3-AFFORD-1102" },
                        color = SurfaceElevated,
                        shape = RoundedCornerShape(4.dp),
                        modifier = Modifier.weight(1f)
                    ) {
                        Text("L3 Affordable", fontSize = 9.sp, fontWeight = FontWeight.Bold, color = AccentNeonGreen, modifier = Modifier.padding(4.dp))
                    }
                }

                resultMessage?.let { msg ->
                    Spacer(modifier = Modifier.height(10.dp))
                    Surface(
                        color = if (isSuccess) AccentNeonGreen.copy(alpha = 0.15f) else DangerRed.copy(alpha = 0.15f),
                        shape = RoundedCornerShape(8.dp),
                        border = androidx.compose.foundation.BorderStroke(1.dp, if (isSuccess) AccentNeonGreen else DangerRed),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Text(
                            text = msg,
                            color = if (isSuccess) AccentNeonGreen else DangerRed,
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold,
                            modifier = Modifier.padding(8.dp)
                        )
                    }
                }

                Spacer(modifier = Modifier.height(16.dp))

                Button(
                    onClick = {
                        val res = authManager.redeemToken(tokenInput)
                        if (res.isSuccess) {
                            val tier = res.getOrThrow()
                            isSuccess = true
                            resultMessage = if (isSwahili) "Hongera! Token ya ${tier.titleSwahili} imewashwa kikamilifu!" else "Success! ${tier.titleEn} activated!"
                        } else {
                            isSuccess = false
                            resultMessage = res.exceptionOrNull()?.message ?: "Token batili. Tafadhali hakiki tena."
                        }
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = AccentGold, contentColor = Color.Black),
                    shape = RoundedCornerShape(10.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Icon(Icons.Default.Check, contentDescription = null, modifier = Modifier.size(16.dp))
                    Spacer(modifier = Modifier.width(6.dp))
                    Text(if (isSwahili) "Washa Token Sasa" else "Activate Token", fontWeight = FontWeight.Black)
                }
            }
        }
    }
}
